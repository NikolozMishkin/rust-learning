/*
-------------------------------------------------------------------------------------------------------------
Концепция / Тема           | Объяснение
---------------------------|---------------------------------------------------------------------------------
Запечатанные трейты        | Запечатанные (sealed) трейты ограничивают круг типов, которые могут реализовать трейт.
(Sealed Traits)            | Они открывают функциональность, но запрещают реализации извне.
                           | Это обеспечивает согласованность и исключает непредусмотренное поведение.

Роль приватных модулей     | Трейт Sealed объявляется в приватном подмодуле.
                           | Трейт Sealed делается супертрейтом того трейта, который мы хотим запечатать.
                           | pub-элементы приватного дочернего модуля видны только родительскому модулю.
                           | Поэтому внешние крейты не могут ни обратиться к трейту Sealed, ни реализовать его.

Влияние на реализацию      | Типы внутри модуля, где объявлены трейты, могут реализовать и Sealed, и публичный трейт.
                           | Типы вне модуля не могут удовлетворить ограничение супертрейта Sealed.
                           | При нарушении компилятор сообщает, что трейт запечатан (sealed).

Доступ vs реализация       | Методы запечатанного трейта по-прежнему можно вызывать вне модуля.
                           | Ограничивается только реализация, а не использование.
                           | Пользователи должны работать с уже предоставленными типами, реализующими трейт.
-------------------------------------------------------------------------------------------------------------
*/
