    <MyType1 as SomeTrait>::some_fn(&a);

    // 3. Вызвать ассоциированную функцию NonSealedTrait у MyType2
    MyType2::open_for_implementation();
    <MyType2 as NonSealedTrait>::open_for_implementation();

    // 4. Использовать SomeTrait как ограничение / trait object
    let v: Vec<Box<dyn SomeTrait>> = vec![Box::new(MyType1)];
