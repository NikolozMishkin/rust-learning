// ===========================================================================
// Урок: сырые указатели (*const / *mut), разыменование, null,
//       и где живёт память — стек vs куча.
//
// Всё можно запустить:  cargo run -p learn_pointers
// И увидеть РЕАЛЬНЫЕ адреса через println!("{:p}", p).
//
// Полезно знать про адреса:
//   - На 64-битной системе адрес — это 8 байт (u64), печатается как 0x....
//   - Стек обычно живёт "высоко" (большие адреса), куча — "ниже".
//     Точные числа зависят от ОС и запуска, но соотношение видно наглядно.
// ===========================================================================

use std::mem::size_of;

fn main() {
    part1_stack_addresses();
    part2_const_vs_mut();
    part3_deref_needs_unsafe();
    part4_null_pointer();
    part5_stack_vs_heap();
    part6_reference_vs_raw();
    part7_unit_pointer();
}

// ---------------------------------------------------------------------------
// 1. Указатель — это просто адрес. Смотрим адреса переменных на стеке.
// ---------------------------------------------------------------------------
fn part1_stack_addresses() {
    println!("=== 1. Переменные на стеке и их адреса ===");

    let a: i32 = 10;
    let b: i32 = 20;
    let c: i32 = 30;

    // Чтобы напечатать адрес в разных системах счисления, превращаем
    // ссылку в число: &a -> *const i32 -> usize (это и есть "адрес как число").
    // Форматы: {:p} = указатель (hex), {} = 10-чная, {:x} = 16-ричная, {:b} = 2-ичная.
    for (name, addr) in [
        ("&a", &a as *const i32 as usize),
        ("&b", &b as *const i32 as usize),
        ("&c", &c as *const i32 as usize),
    ] {
        println!("{name}:");
        println!("  hex  (16) = 0x{addr:x}");
        println!("  dec  (10) = {addr}");
        println!("  bin  (2)  = 0b{addr:b}");
    }
    println!("-> три i32 лежат рядом на стеке, адреса отличаются на 4 (=100 в двоичной)\n");
}

// ---------------------------------------------------------------------------
// 2. *const (только чтение) vs *mut (чтение + запись).
// ---------------------------------------------------------------------------
fn part2_const_vs_mut() {
    println!("=== 2. *const T vs *mut T ===");

    let mut x: i32 = 42;

    // Из одной и той же переменной делаем два разных сырых указателя.
    let p_const: *const i32 = &x;      // read-only
    let p_mut: *mut i32 = &mut x;      // read + write

    println!("p_const = {p_const:p}  (только чтение)");
    println!("p_mut   = {p_mut:p}  (чтение и запись)");
    println!("оба указывают на один и тот же x -> адреса совпадают");

    unsafe {
        // Через *const можно только читать:
        let read = *p_const;
        println!("прочитали через *p_const = {read}");

        // Через *mut можно писать:
        *p_mut = 100;
        println!("записали через *p_mut, теперь x = {x}");

        // *p_const = 5;  // <- НЕ скомпилируется: нельзя писать через *const
    }
    println!();
}

// ---------------------------------------------------------------------------
// 3. Разыменование сырого указателя требует unsafe.
// ---------------------------------------------------------------------------
fn part3_deref_needs_unsafe() {
    println!("=== 3. Разыменование (*p) требует unsafe ===");

    let value = 7;
    let p: *const i32 = &value;

    // let bad = *p;             // <- ошибка компиляции без unsafe
    let good = unsafe { *p };    // <- ок: мы взяли ответственность на себя

    println!("p указывает на {good}");
    println!("-> компилятор не гарантирует валидность сырого указателя,");
    println!("   поэтому * разрешён только в unsafe-блоке\n");
}

// ---------------------------------------------------------------------------
// 4. Null-указатель: сырой может показывать "в никуда". Ссылка так не умеет.
// ---------------------------------------------------------------------------
fn part4_null_pointer() {
    println!("=== 4. Null-указатель ===");

    let p: *const i32 = std::ptr::null();

    println!("p = {p:p}  (это адрес 0x0)");
    println!("p.is_null() = {}", p.is_null());

    // Разыменовать null = UB (undefined behavior), поэтому НЕ делаем *p.
    // Правильный способ — проверить и не трогать:
    if p.is_null() {
        println!("указатель null -> разыменовывать НЕЛЬЗЯ, пропускаем");
    }
    println!("-> у ссылок (&T) null невозможен в принципе\n");
}

// ---------------------------------------------------------------------------
// 5. Стек vs куча: сам указатель на стеке, а данные могут быть где угодно.
// ---------------------------------------------------------------------------
fn part5_stack_vs_heap() {
    println!("=== 5. Стек vs куча ===");

    // Данные на стеке:
    let on_stack: i32 = 1;
    let p_stack: *const i32 = &on_stack;

    // Данные в куче (Box кладёт значение в кучу):
    let on_heap: Box<i32> = Box::new(2);
    let p_heap: *const i32 = &*on_heap;   // адрес данных ВНУТРИ кучи

    // Адрес самого указателя p_heap (он-то живёт на стеке):
    let p_heap_self: *const *const i32 = &p_heap;

    println!("данные на стеке:  адрес = {p_stack:p}");
    println!("данные в куче:    адрес = {p_heap:p}");
    println!("сам указатель p_heap лежит на стеке по адресу = {p_heap_self:p}");
    println!("-> заметь: адрес данных в куче обычно СИЛЬНО отличается");
    println!("   от стековых адресов (разные области памяти)");
    println!("-> но САМ указатель (8 байт) всегда на стеке\n");
}

// ---------------------------------------------------------------------------
// 6. Ссылка (&) vs сырой указатель (*const): физически одно и то же,
//    отличаются гарантиями и авто-приведением.
// ---------------------------------------------------------------------------
fn part6_reference_vs_raw() {
    println!("=== 6. Ссылка & vs сырой указатель * ===");

    let x = 55;

    let r: &i32 = &x;                    // ссылка (безопасная)
    let p: *const i32 = r;               // ссылка -> сырой указатель: авто, безопасно

    println!("ссылка r        = {:p}", r);
    println!("сырой из неё p  = {:p}", p);
    println!("адрес тот же -> внутри это одно и то же число");

    // Обратно (сырой -> ссылка) только через unsafe:
    let r2: &i32 = unsafe { &*p };
    println!("вернули ссылку через unsafe: *r2 = {}", *r2);

    println!("размеры: &i32 = {} байт, *const i32 = {} байт (одинаково)\n",
        size_of::<&i32>(), size_of::<*const i32>());
}

// ---------------------------------------------------------------------------
// 7. *const () — указатель на unit type. "Адрес непонятно на что" (как void*).
// ---------------------------------------------------------------------------
fn part7_unit_pointer() {
    println!("=== 7. *const () — указатель со стёртым типом (аналог void*) ===");

    let x: i32 = 999;

    // Берём адрес i32 и "забываем" тип, приведя к *const ().
    let typed: *const i32 = &x;
    let erased: *const () = typed as *const ();

    println!("typed  (*const i32) = {typed:p}");
    println!("erased (*const ())  = {erased:p}");
    println!("адрес тот же — поменялся только ТИП указателя, не значение");

    // Чтобы снова прочитать данные, надо вернуть тип обратно:
    let back: *const i32 = erased as *const i32;
    let value = unsafe { *back };
    println!("вернули тип и прочитали: {value}");

    println!("размеры: *const () = {} байт, sizeof(()) = {} байт",
        size_of::<*const ()>(), size_of::<()>());
    println!("-> сам () весит 0 байт, но УКАЗАТЕЛЬ на него — всё равно 8 байт");
    println!("-> именно такой маркер (*const ()) снимает Send/Sync без lifetime");
}
